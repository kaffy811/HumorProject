// Local in-memory check of the superadmin migration. Never connects to a deployed database.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';
const db=new PGlite();
try {
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;
  create table auth.users(id uuid primary key);grant usage on schema auth to authenticated,service_role;
  create function auth.uid()returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  create function auth.jwt()returns jsonb language sql as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
  create table public.profiles(id uuid primary key references auth.users(id),username text,first_name text);
  alter table public.profiles enable row level security;
  grant usage on schema public to authenticated,service_role;
  grant select on public.profiles to authenticated;grant update(first_name,username) on public.profiles to authenticated;
  grant all on public.profiles to service_role;
  create policy "Read own profile" on public.profiles for select to authenticated using(id=(select auth.uid()));
  create policy "Update own profile" on public.profiles for update to authenticated using(id=(select auth.uid())) with check(id=(select auth.uid()));`);
 await db.exec(await readFile('supabase/migrations/202610200001_superadmin.sql','utf8'));
 await db.exec(await readFile('supabase/migrations/202610210001_superadmin_requests.sql','utf8'));
 const member=randomUUID();
 await db.query('insert into auth.users(id)values($1)',[member]);
 await db.query('insert into public.profiles(id)values($1)',[member]);
 assert.equal((await db.query('select is_superadmin from public.profiles where id=$1',[member])).rows[0].is_superadmin,false);
 const asMember=async()=>{await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)",[member,JSON.stringify({sub:member,role:'authenticated'})]);await db.exec('set role authenticated');};
 await asMember();
 await assert.rejects(()=>db.query('update public.profiles set is_superadmin=true where id=$1',[member]),/permission denied/);
 await db.query("update public.profiles set first_name='Still editable' where id=$1",[member]);
 await db.exec('reset role');
 // Even a future broad grant cannot let a member promote itself.
 await db.exec('grant update on public.profiles to authenticated');
 await asMember();
 await assert.rejects(()=>db.query('update public.profiles set is_superadmin=true where id=$1',[member]),/database owner/);
 await db.exec('reset role');
 await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({role:'service_role'})]);
 await db.exec('set role service_role');
 await db.query('update public.profiles set is_superadmin=true where id=$1',[member]);
 await db.exec('reset role');
 assert.equal((await db.query('select is_superadmin from public.profiles where id=$1',[member])).rows[0].is_superadmin,true);
 // Request → approval flow.
 const applicant=randomUUID(),outsider=randomUUID();
 for(const id of [applicant,outsider]){await db.query('insert into auth.users(id)values($1)',[id]);await db.query('insert into public.profiles(id)values($1)',[id]);}
 const req=(await db.query("insert into public.humor_admin_requests(user_id,message)values($1,'please')returning id",[applicant])).rows[0].id;
 await assert.rejects(()=>db.query('insert into public.humor_admin_requests(user_id)values($1)',[applicant]),/duplicate key/);
 await assert.rejects(()=>db.query('select public.humor_decide_admin_request($1,$2,true)',[req,outsider]),/Only superadmins/);
 await db.exec('set role authenticated');
 await assert.rejects(()=>db.query('select * from public.humor_admin_requests'),/permission denied/);
 await assert.rejects(()=>db.query('select public.humor_decide_admin_request($1,$2,true)',[req,member]),/permission denied/);
 await db.exec('reset role');
 const decided=(await db.query('select public.humor_decide_admin_request($1,$2,true)r',[req,member])).rows[0].r;
 assert.equal(decided.status,'approved');
 assert.equal((await db.query('select is_superadmin from public.profiles where id=$1',[applicant])).rows[0].is_superadmin,true);
 await assert.rejects(()=>db.query('select public.humor_decide_admin_request($1,$2,false)',[req,member]),/already decided/);
 const second=(await db.query('insert into public.humor_admin_requests(user_id)values($1)returning id',[outsider])).rows[0].id;
 assert.equal((await db.query('select public.humor_decide_admin_request($1,$2,false)r',[second,member])).rows[0].r.status,'rejected');
 assert.equal((await db.query('select is_superadmin from public.profiles where id=$1',[outsider])).rows[0].is_superadmin,false);
 await db.query('insert into public.humor_admin_requests(user_id)values($1)',[outsider]);
 // Roles: approved requesters become admins; superadmins approve and remove admins.
 await db.exec(await readFile('supabase/migrations/202610230001_admin_roles.sql','utf8'));
 const role=async(id)=>(await db.query('select is_superadmin s,is_admin a from public.profiles where id=$1',[id])).rows[0];
 assert.deepEqual(await role(applicant),{s:false,a:true},'approved requester converted to admin');
 assert.deepEqual(await role(member),{s:true,a:false},'the approver stays superadmin');
 const third=randomUUID();
 await db.query('insert into auth.users(id)values($1)',[third]);await db.query('insert into public.profiles(id)values($1)',[third]);
 const r3=(await db.query('insert into public.humor_admin_requests(user_id)values($1)returning id',[third])).rows[0].id;
 await assert.rejects(()=>db.query('select public.humor_decide_admin_request($1,$2,true)',[r3,applicant]),/Only superadmins/,'admins cannot approve');
 await db.query('select public.humor_decide_admin_request($1,$2,true)',[r3,member]);
 assert.deepEqual(await role(third),{s:false,a:true},'approval grants admin, not superadmin');
 await assert.rejects(()=>db.query('select public.humor_revoke_admin($1,$2)',[third,applicant]),/Only superadmins/,'admins cannot remove admins');
 await assert.rejects(()=>db.query('select public.humor_revoke_admin($1,$2)',[member,member]),/database owner/,'superadmins cannot be removed from the console');
 await db.query('insert into public.humor_admin_requests(user_id)values($1)',[third]);
 await db.query('select public.humor_revoke_admin($1,$2)',[third,member]);
 assert.deepEqual(await role(third),{s:false,a:false},'removed admin loses access');
 assert.equal((await db.query("select count(*)::int n from public.humor_admin_requests where user_id=$1 and status='pending'",[third])).rows[0].n,0,'their pending request is closed');
 await assert.rejects(()=>db.query('select public.humor_revoke_admin($1,$2)',[third,member]),/not an admin/);
 await asMember();
 await assert.rejects(()=>db.query('update public.profiles set is_admin=true where id=$1',[member]),/permission denied|superadmin or database owner/);
 await db.exec('reset role');
 console.log('PASS superadmin flag defaults false, members cannot grant it (column grant + trigger), service role and owners can; one pending request per member, only superadmins decide, decisions are final and atomic; approvals grant admin, only superadmins approve or remove admins, superadmins cannot be removed.');
} finally { await db.close(); }
